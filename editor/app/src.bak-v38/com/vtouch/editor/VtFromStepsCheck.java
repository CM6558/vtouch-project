    /* ================= 工具 ================= */

    private static Ops.Step st(int type, int a1, int a2, int a3, int a4, int ms, String ref, int j1, int j2, String expr) {
        Ops.Step s = new Ops.Step();
        s.type = type; s.a1 = a1; s.a2 = a2; s.a3 = a3; s.a4 = a4; s.ms = ms;
        s.ref = ref; s.j1 = j1; s.j2 = j2; s.expr = expr;
        return s;
    }

    /** 条件步 10（找图 tm）快捷构造：a3=不成立档、a4=成立档、j1/j2=跳转目标。 */
    private static Ops.Step c10(int a4, int a3, int j1, int j2) {
        return st(10, 8, 0, a3, a4, 0, "tm", j1, j2, "");
    }

    private static Ops.Step tap() { return st(1, 1, 2, 0, 0, 50, "", 0, 0, ""); }

    private static Ops.Step raw(String line) {
        Ops.Step s = new Ops.Step();
        s.raw = line;
        return s;
    }

    private static Ops.Op op(Ops.Step... ss) {
        Ops.Op o = new Ops.Op();
        o.name = "op1";
        o.gate = "-";
        o.autooff = 0;
        for (Ops.Step s : ss) o.steps.add(s);
        return o;
    }

    private static void eq(String name, Ops.Op o, String expect) {
        VtFromSteps.R r = VtFromSteps.translate(o);
        if (!r.problems.isEmpty()) { bad0(name, "problems=" + r.problems); return; }
        if (expect.equals(r.src)) { ok(name); return; }
        bad0(name, "输出不一致\n--- 期望 ---\n" + expect + "--- 实际 ---\n" + r.src);
    }

    private static void bad(String name, Ops.Op o, String expectSubstr) {
        VtFromSteps.R r = VtFromSteps.translate(o);
        if (r.src != null) { bad0(name, "期望不可译但产出了 src"); return; }
        for (String p : r.problems) if (p.contains(expectSubstr)) { ok(name); return; }
        bad0(name, "problems 未含「" + expectSubstr + "」: " + r.problems);
    }

    private static void ok(String name) { pass++; System.out.println("[OK] " + name); }

    private static void bad0(String name, String why) {
        fail++;
        System.out.println("[FAIL] " + name + " —— " + why);
    }
